// ============================================================================
//  Этап 7. Автопилот v1 — урок 28: SG90 + HC-SR04, сканирующий сонар
// ----------------------------------------------------------------------------
//  Цель: превратить одно число из урока 27 в СЕКТОР — маленький радар. Сервопривод
//  поворачивает датчик по шагам, на каждом шаге меряем расстояние, в конце имеем
//  карту «что и на каком угле впереди». Это и есть вход для автопилота: не
//  «свободно/занято», а «слева стена в 30 см, справа коридор на 2 метра».
//
//  Два новых понятия:
//    1) СЕРВОПРИВОД — это не «мотор». Внутри мотор + редуктор + потенциометр +
//       крошечный контроллер, который сам крутит вал, пока напряжение с
//       потенциометра не совпадёт с заданным. Обратная связь замкнута ВНУТРИ:
//       мы говорим «встань на 90°» и не можем спросить, встал ли он на самом деле.
//    2) ШИМ 50 Гц, где важна ШИРИНА ИМПУЛЬСА, а не скважность: 500 мкс ≈ 0°,
//       1500 мкс ≈ 90° (центр), 2400 мкс ≈ 180°. Период всегда 20 мс. Стандарт
//       достался от радиоуправляемых моделей 1960-х, где импульс был буквально
//       слотом в радиокадре.
//
//  Библиотека Servo здесь СПЕЦИАЛЬНО не используется: весь сервопривод — это
//  ledcSetup(канал, 50, 16) + пересчёт микросекунд в duty. Так видно, что
//  «управление сервоприводом» и «PWM из урока 3» — одно и то же.
//
//  Порядок на каждом шаге строго такой: ПОВЕРНУТЬ -> ПОДОЖДАТЬ -> МЕРИТЬ.
//  Мерить во время движения нельзя: датчик едет, конус ползёт, и вдобавок мотор
//  сервопривода создаёт помеху и просадку питания. Отсюда главная плата за
//  сканирование — ВРЕМЯ (полный проход ≈ 2 секунды, см. вывод в Serial).
//
//  Подключение (см. include/pins.h и documentation/lesson28_servo_sonar.md):
//    HC-SR04: VCC -> 5V, GND -> GND, TRIG -> GPIO12,
//             ECHO -> ДЕЛИТЕЛЬ 1к/2к -> GPIO39;
//    SG90:    красный -> 5V (ОТДЕЛЬНАЯ шина, не 3V3!), коричневый -> GND,
//             оранжевый (сигнал) -> GPIO19.
//
//  Сборка:  pio run -e lesson28_servo_sonar -t upload && pio device monitor
// ============================================================================

#include <Arduino.h>
#include "pins.h"

// ---- Сервопривод ----------------------------------------------------------
const uint32_t SERVO_FREQ_HZ = 50;      // 20 мс период — стандарт хобби-сервоприводов
const uint8_t  SERVO_BITS    = 16;      // разрешение LEDC: 65535 шагов на 20 мс ≈ 0.3 мкс
const uint16_t SERVO_MIN_US  = 500;     // ~0°   (паспорт SG90: 500..2400)
const uint16_t SERVO_MAX_US  = 2400;    // ~180°

// Реальные SG90 гуляют от партии к партии: у одного 0° это 480 мкс, у другого 600.
// В упор к механическому концу лучше не ходить — привод упрётся, зажужжит и будет
// греться. Поэтому сканируем не 0..180, а с запасом.
const uint8_t SCAN_MIN_DEG  = 30;
const uint8_t SCAN_MAX_DEG  = 150;
const uint8_t SCAN_STEP_DEG = 15;                                     // 9 точек
const uint8_t SCAN_POINTS   = (SCAN_MAX_DEG - SCAN_MIN_DEG) / SCAN_STEP_DEG + 1;

// Сколько ждать после команды поворота. SG90 идёт ~0.1 с на 60°, то есть шаг в
// 15° — это ~25 мс хода плюс качание вала около новой точки. 120 мс с запасом.
const uint32_t SETTLE_MS = 120;

// ---- Сонар (та же физика, что в уроке 27) ---------------------------------
const float    AIR_TEMP_C      = 20.0f;    // v = 331.4 + 0.606*T (м/с)
const float    MIN_VALID_CM    = 2.0f;
const float    MAX_VALID_CM    = 400.0f;
const uint32_t ECHO_TIMEOUT_US = 30000UL;
const uint32_t PING_GAP_MS     = 60;       // требование даташита между «пиками»
const uint8_t  PINGS_PER_POINT = 3;        // медиана из 3 на каждом угле
const float    STOP_CM         = 20.0f;    // порог автопилота Этапа 7

// Результат последнего прохода: NAN = «эха не было», НЕ «свободно».
float scan[SCAN_POINTS];

bool sweepForward = true;   // «пинг-понг»: чередуем направление прохода

float soundCmPerUs() {
  return (331.4f + 0.606f * AIR_TEMP_C) / 10000.0f;
}

// ---------------------------------------------------------------------------
//  Угол -> ширина импульса -> duty канала LEDC.
//  duty = ширина / период * (2^bits - 1), период при 50 Гц = 20000 мкс.
// ---------------------------------------------------------------------------
uint32_t usToDuty(uint32_t us) {
  return (uint32_t)(((uint64_t)us * ((1UL << SERVO_BITS) - 1)) / 20000UL);
}

void servoWriteDeg(float deg) {
  deg = constrain(deg, 0.0f, 180.0f);
  uint32_t us = SERVO_MIN_US + (uint32_t)((SERVO_MAX_US - SERVO_MIN_US) * deg / 180.0f);
  ledcWrite(CH_SERVO, usToDuty(us));
}

// ---------------------------------------------------------------------------
//  Снять с канала импульсы. Сервопривод теряет момент удержания и «отпускает»
//  вал: перестаёт жужжать, гудеть и есть ток. Хорошая привычка, когда позиция
//  какое-то время не нужна; на роботе с батареей — ещё и экономия.
// ---------------------------------------------------------------------------
void servoRelax() {
  ledcWrite(CH_SERVO, 0);
}

// ---------------------------------------------------------------------------
//  Одно измерение сонара. NAN = ответа нет (см. урок 27: это ТРЕТЬЕ состояние,
//  а не «далеко»).
// ---------------------------------------------------------------------------
float pingCm() {
  digitalWrite(SONAR_TRIG, LOW);
  delayMicroseconds(4);
  digitalWrite(SONAR_TRIG, HIGH);
  delayMicroseconds(10);
  digitalWrite(SONAR_TRIG, LOW);

  uint32_t us = pulseIn(SONAR_ECHO, HIGH, ECHO_TIMEOUT_US);
  if (us == 0) return NAN;

  float cm = us * soundCmPerUs() / 2.0f;
  if (cm < MIN_VALID_CM || cm > MAX_VALID_CM) return NAN;
  return cm;
}

// ---------------------------------------------------------------------------
//  Медиана нескольких «пиков» на одном угле. Тайм-ауты выбрасываем; если
//  валидных меньше двух — точка остаётся «не знаю».
// ---------------------------------------------------------------------------
float measurePointCm() {
  float v[PINGS_PER_POINT];
  uint8_t n = 0;

  for (uint8_t i = 0; i < PINGS_PER_POINT; i++) {
    if (i) delay(PING_GAP_MS);       // не чаще, чем раз в 60 мс
    float cm = pingCm();
    if (!isnan(cm)) v[n++] = cm;
  }
  if (n < 2) return NAN;

  for (uint8_t i = 1; i < n; i++) {  // сортировка вставками, элементов единицы
    float key = v[i];
    int8_t j = i - 1;
    while (j >= 0 && v[j] > key) { v[j + 1] = v[j]; j--; }
    v[j + 1] = key;
  }
  return v[n / 2];
}

uint8_t angleAt(uint8_t index) {
  return SCAN_MIN_DEG + index * SCAN_STEP_DEG;
}

// ---------------------------------------------------------------------------
//  Полный проход сектора. Блокирующий — и это осознанно: в этом уроке ничего,
//  кроме сканирования, не происходит. В автопилоте так уже нельзя: пока идёт
//  проход (~2 с), робот не обрабатывает ни MQTT, ни failsafe моторов (700 мс).
//  Там сканирование либо разворачивают в автомат состояний (один шаг за loop()),
//  либо робот сначала ОСТАНАВЛИВАЕТСЯ и только потом смотрит по сторонам —
//  «stop and look», как делают все дешёвые роботы-пылесосы.
// ---------------------------------------------------------------------------
void sweep() {
  for (uint8_t k = 0; k < SCAN_POINTS; k++) {
    // Пинг-понг: назад едем по тем же углам в обратном порядке, чтобы не гонять
    // привод через весь сектор вхолостую.
    uint8_t i = sweepForward ? k : (SCAN_POINTS - 1 - k);

    servoWriteDeg(angleAt(i));
    delay(SETTLE_MS);                // ПОВЕРНУТЬ -> ПОДОЖДАТЬ -> МЕРИТЬ
    scan[i] = measurePointCm();
  }
  sweepForward = !sweepForward;
}

// ---------------------------------------------------------------------------
//  Печать сектора «радаром»: полоска длиной пропорционально расстоянию.
// ---------------------------------------------------------------------------
void printScan(uint32_t sweepMs) {
  float best = NAN;   uint8_t bestDeg = 0;    // самое дальнее — куда ехать
  float near_ = NAN;  uint8_t nearDeg = 0;    // самое близкое — чего бояться
  uint8_t unknown = 0;

  Serial.println("---------------------------------------------");
  for (uint8_t i = 0; i < SCAN_POINTS; i++) {
    uint8_t deg = angleAt(i);
    float cm = scan[i];

    if (isnan(cm)) {
      unknown++;
      Serial.printf("%4u°  |  нет эха   |\n", deg);
      continue;
    }

    // Шкала: 10 см на символ, максимум 20 символов (200 см и дальше).
    uint8_t bars = (uint8_t)constrain((int)(cm / 10.0f), 1, 20);
    char bar[21];
    memset(bar, '#', bars);
    bar[bars] = '\0';

    Serial.printf("%4u°  | %6.1f см  |%s%s\n", deg, cm, bar,
                  cm < STOP_CM ? "  <-- близко" : "");

    if (isnan(best)  || cm > best)  { best  = cm; bestDeg = deg; }
    if (isnan(near_) || cm < near_) { near_ = cm; nearDeg = deg; }
  }
  Serial.println("---------------------------------------------");

  if (isnan(best)) {
    // Ни одной валидной точки за весь проход. Для автопилота это НЕ «кругом
    // чисто», а «я ослеп»: так выглядит и стена под углом, и оторвавшийся датчик.
    Serial.println("весь сектор без эха — двигаться вслепую НЕЛЬЗЯ");
  } else {
    Serial.printf("свободнее всего: %u° (%.0f см)   ближайшее: %u° (%.0f см)\n",
                  bestDeg, best, nearDeg, near_);
    if (near_ < STOP_CM)
      Serial.println("автопилот бы тормозил и поворачивал в сторону свободного угла");
  }
  if (unknown)
    Serial.printf("точек без ответа: %u из %u — это «не знаю», а не «свободно»\n",
                  unknown, SCAN_POINTS);
  Serial.printf("проход занял %lu мс\n\n", (unsigned long)sweepMs);
}

void setup() {
  Serial.begin(115200);
  delay(300);

  // Сонар — как в уроке 27.
  pinMode(SONAR_TRIG, OUTPUT);
  digitalWrite(SONAR_TRIG, LOW);
  pinMode(SONAR_ECHO, INPUT);          // GPIO39 — вход-only, без подтяжек

  // Сервопривод: ШИМ 50 Гц, 16 бит. Канал 4 (таймер 2 — ch/2 в ядре 2.x),
  // чтобы не пересечься с RGB/buzzer на каналах 0..2.
  ledcSetup(CH_SERVO, SERVO_FREQ_HZ, SERVO_BITS);
  ledcAttachPin(SERVO_PIN, CH_SERVO);

  for (uint8_t i = 0; i < SCAN_POINTS; i++) scan[i] = NAN;

  Serial.println("\n=== Урок 28. Сканирующий сонар (SG90 + HC-SR04) ===");
  Serial.printf("сектор %u..%u° шагом %u° = %u точек, по %u «пика» на точку\n",
                SCAN_MIN_DEG, SCAN_MAX_DEG, SCAN_STEP_DEG, SCAN_POINTS, PINGS_PER_POINT);
  Serial.printf("импульс %u..%u мкс при %lu Гц (центр ~1500 мкс = 90°)\n",
                SERVO_MIN_US, SERVO_MAX_US, (unsigned long)SERVO_FREQ_HZ);

  // Встаём в центр и даём приводу спокойно доехать: при подаче питания вал
  // прыгает в заданную позицию рывком, и это самый большой бросок тока.
  servoWriteDeg(90);
  delay(600);
  Serial.println("центр 90° — проверь, что датчик смотрит строго вперёд.\n");
}

void loop() {
  uint32_t t0 = millis();
  sweep();
  uint32_t sweepMs = millis() - t0;

  printScan(sweepMs);

  // Между проходами отпускаем вал: жужжание пропадает, ток падает почти до нуля.
  // Заодно слышно разницу — это и есть удержание позиции.
  servoRelax();
  delay(1000);
}
