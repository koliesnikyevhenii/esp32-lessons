// ============================================================================
//  Этап 7. Автопилот v1 — урок 27: HC-SR04, ультразвуковой дальномер
// ----------------------------------------------------------------------------
//  Цель: научиться мерить расстояние до препятствия «как летучая мышь» — послать
//  пачку ультразвука и засечь, через сколько вернулось эхо. Ни Wi-Fi, ни MQTT,
//  ни моторов: сначала железо и физика, потом сканер на сервоприводе (урок 28)
//  и автопилот (урок 29).
//
//  Датчик НЕ измеряет расстояние. Он измеряет ВРЕМЯ. Расстояние мы считаем сами,
//  подставив скорость звука — а она зависит от температуры воздуха. Отсюда почти
//  все «странности» HC-SR04, и отсюда же половина этого урока.
//
//  Как работает модуль:
//    1) мы дёргаем TRIG в HIGH ровно на 10 мкс;
//    2) модуль сам излучает 8 периодов на 40 кГц («пачку») и поднимает ECHO;
//    3) как только вернулось эхо — опускает ECHO.
//    Длительность HIGH на ECHO = время полёта туда-обратно.
//
//        расстояние[см] = время[мкс] * скорость_звука[см/мкс] / 2
//
//    При 20 °C звук идёт 343 м/с = 0.0343 см/мкс, значит 1 см «стоит» 29 мкс в
//    одну сторону и 58 мкс туда-обратно. Отсюда знаменитая формула «/58».
//
//  Что нового по сравнению с уроками 8/9 (PIR и ИК-датчик препятствий):
//    • те датчики отвечают «есть/нет», этот — числом в сантиметрах;
//    • измерение занимает ВРЕМЯ (до 30 мс), и это накладывает потолок на частоту
//      опроса — физику не обойти;
//    • у измерения есть «нет ответа» (тайм-аут). Это ТРЕТЬЕ состояние, и путать
//      его с «дорога свободна» — главная ошибка автопилота (см. ниже).
//
//  Подключение (см. include/pins.h и documentation/lesson27_hcsr04.md):
//    VCC  -> 5V (VIN платы), GND -> GND,
//    TRIG -> GPIO12,
//    ECHO -> ДЕЛИТЕЛЬ 1к/2к -> GPIO39.  Пины ESP32 не 5-вольтовые!
//
//  Сборка:  pio run -e lesson27_hcsr04 -t upload && pio device monitor
// ============================================================================

#include <Arduino.h>
#include "pins.h"

// ---- Физика ----------------------------------------------------------------
// Скорость звука в воздухе: v = 331.4 + 0.606*T (м/с, T в °C). Разница между
// 0 °C и +30 °C — около 5 %: на дистанции 2 м это 10 см ошибки. Для автопилота
// с порогом «стена ближе 20 см» это неважно, для рулетки — критично.
// Дальше можно брать T с MPU6050 (у него есть встроенный термометр) или с DHT11.
const float AIR_TEMP_C = 20.0f;

// ---- Границы измерения -----------------------------------------------------
// Ниже 2 см датчик слеп физически: пачка из 8 периодов 40 кГц длится 200 мкс,
// за это время звук успевает пройти ~7 см (то есть до отражателя ~3 см), плюс
// пьезоизлучатель ещё «звенит». Пока он звенит — приёмник глухой.
const float MIN_VALID_CM = 2.0f;
const float MAX_VALID_CM = 400.0f;   // паспортный потолок; дальше эхо слишком слабое

// Тайм-аут ожидания эха. 400 см = 400*58 = 23200 мкс, берём с запасом.
// Если эха нет вовсе — pulseIn вернёт 0, и это НЕ «пусто впереди», а «не знаю».
const uint32_t ECHO_TIMEOUT_US = 30000UL;

// Пауза между «пиками». Даташит требует не чаще одного раза в 60 мс: иначе в
// следующее измерение прилетит эхо от ПРЕДЫДУЩЕГО, отражённое от дальней стены,
// и датчик покажет ерунду (обычно — неправдоподобно близко).
const uint32_t PING_PERIOD_MS = 60;

// Порог автопилота из Этапа 7 — здесь только для наглядной надписи в Serial.
const float STOP_CM = 20.0f;

// Скользящее окно последних измерений: медиана из 3 убивает одиночные выбросы
// (переотражение от угла, помеха от моторов), но почти не добавляет задержки —
// в отличие от усреднения, которое «размазывает» настоящее приближение стены.
const uint8_t WINDOW = 3;
float window[WINDOW];
uint8_t windowPos = 0;
bool windowFilled = false;

uint32_t lastPing = 0;
uint32_t lastPrint = 0;
const uint32_t PRINT_PERIOD_MS = 500;

// Счётчики — по ним сразу видно качество установки датчика.
uint32_t pings = 0, timeouts = 0;

// ---------------------------------------------------------------------------
//  Скорость звука в см/мкс при текущей температуре.
// ---------------------------------------------------------------------------
float soundCmPerUs() {
  return (331.4f + 0.606f * AIR_TEMP_C) / 10000.0f;   // м/с -> см/мкс
}

// ---------------------------------------------------------------------------
//  Одно измерение. Возвращает расстояние в см или NAN, если ответа нет.
//
//  pulseIn БЛОКИРУЮЩАЯ: она честно крутит цикл до конца импульса или до
//  тайм-аута, то есть в худшем случае съедает все 30 мс. В этом уроке моторов
//  нет и это не мешает; в автопилоте так делать уже нельзя — там нужен либо
//  короткий тайм-аут (порог 20 см = 1160 мкс, можно ставить ~10 мс на 1.7 м),
//  либо измерение по прерыванию/через RMT. Разбор — в документации урока.
// ---------------------------------------------------------------------------
float measureCm() {
  // Гарантируем чистый фронт: сначала LOW, потом ровно 10 мкс HIGH.
  digitalWrite(SONAR_TRIG, LOW);
  delayMicroseconds(4);
  digitalWrite(SONAR_TRIG, HIGH);
  delayMicroseconds(10);
  digitalWrite(SONAR_TRIG, LOW);

  uint32_t us = pulseIn(SONAR_ECHO, HIGH, ECHO_TIMEOUT_US);
  pings++;

  if (us == 0) {           // тайм-аут: эхо не вернулось
    timeouts++;
    return NAN;
  }

  float cm = us * soundCmPerUs() / 2.0f;   // /2 — звук слетал ТУДА И ОБРАТНО

  // Вне паспортного диапазона показаниям верить нельзя: ближе 2 см датчик слеп,
  // дальше 4 м эхо тонет в шуме. Возвращаем «не знаю», а не красивое число.
  if (cm < MIN_VALID_CM || cm > MAX_VALID_CM) return NAN;
  return cm;
}

// ---------------------------------------------------------------------------
//  Медиана окна. NAN-ы (тайм-ауты) в расчёт не берём; если валидных значений
//  меньше двух — считаем, что расстояния мы не знаем.
// ---------------------------------------------------------------------------
float medianCm() {
  float v[WINDOW];
  uint8_t n = 0;
  uint8_t count = windowFilled ? WINDOW : windowPos;
  for (uint8_t i = 0; i < count; i++) {
    if (!isnan(window[i])) v[n++] = window[i];
  }
  if (n < 2) return NAN;

  // Сортировка вставками — на трёх элементах это дешевле любой библиотеки.
  for (uint8_t i = 1; i < n; i++) {
    float key = v[i];
    int8_t j = i - 1;
    while (j >= 0 && v[j] > key) { v[j + 1] = v[j]; j--; }
    v[j + 1] = key;
  }
  return v[n / 2];
}

void setup() {
  Serial.begin(115200);
  delay(300);

  pinMode(SONAR_TRIG, OUTPUT);
  digitalWrite(SONAR_TRIG, LOW);
  // GPIO39 — вход-only и БЕЗ внутренних подтяжек; INPUT здесь единственный
  // допустимый режим, уровень на линии держит делитель от ECHO.
  pinMode(SONAR_ECHO, INPUT);

  for (uint8_t i = 0; i < WINDOW; i++) window[i] = NAN;

  Serial.println("\n=== Урок 27. HC-SR04 ===");
  Serial.printf("Температура принята за %.1f C -> скорость звука %.1f м/с (%.0f мкс на см туда-обратно)\n",
                AIR_TEMP_C, 331.4f + 0.606f * AIR_TEMP_C, 2.0f / soundCmPerUs());
  Serial.printf("Рабочий диапазон %.0f..%.0f см, опрос раз в %lu мс.\n",
                MIN_VALID_CM, MAX_VALID_CM, (unsigned long)PING_PERIOD_MS);
  Serial.println("Поднеси ладонь и отводи её — смотри, где показания станут рваными.\n");
}

void loop() {
  uint32_t now = millis();

  // «Пикаем» не чаще, чем разрешает даташит.
  if (now - lastPing >= PING_PERIOD_MS) {
    lastPing = now;
    window[windowPos] = measureCm();
    windowPos = (windowPos + 1) % WINDOW;
    if (windowPos == 0) windowFilled = true;
  }

  // Печатаем реже, чем меряем: 16 строк в секунду читать невозможно.
  if (now - lastPrint >= PRINT_PERIOD_MS) {
    lastPrint = now;

    uint8_t lastIdx = (windowPos + WINDOW - 1) % WINDOW;
    float raw = window[lastIdx];
    float med = medianCm();

    if (isnan(med)) {
      // Ключевой момент урока: это НЕ «свободно». Эхо не вернулось — а причин
      // три: далеко (>4 м), поверхность отразила звук вбок (стена под углом),
      // или материал звук съел (штора, поролон, кошка). Стена при этом может
      // быть в 30 см прямо перед носом.
      Serial.printf("расстояние: НЕТ ЭХА  (тайм-аутов %lu из %lu)\n",
                    (unsigned long)timeouts, (unsigned long)pings);
    } else {
      char rawText[16];
      if (isnan(raw)) strcpy(rawText, "нет эха");
      else            snprintf(rawText, sizeof(rawText), "%.1f", raw);

      Serial.printf("расстояние: %6.1f см   (последнее измерение: %s)  %s\n",
                    med, rawText,
                    med < STOP_CM ? "<-- ближе порога, автопилот бы тормозил" : "");
    }
  }
}
